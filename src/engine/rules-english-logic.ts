/** Words split on anything that isn't a letter, digit, hyphen or apostrophe (works for any script). */
function words(q: string): string[] {
  return q
    .toLowerCase()
    .split(/[\s.,!?;:()"«»„“”¿¡]+/)
    .filter(Boolean);
}

function hasStem(q: string, stems: string[]): boolean {
  const ws = words(q);
  const joined = ` ${ws.join(' ')} `;
  return stems.some((s) =>
    s.includes(' ')
      ? joined.includes(` ${s} `) || joined.includes(` ${s}`)
      : ws.some((w) => w.startsWith(s)),
  );
}

/** A time, a number or a currency/unit sign: reminders, timers, sums and conversions in any language. */
const NUMBERISH = /\d|[€$£%°]/;

/** True when [question] in [language] may be something the English rules handle. */
export function needsEnglishForRules(question: string, language: string): boolean {
  if (language === 'en') return false;
  const q = question.trim();
  if (!q || q.split(/\s+/).length > 40) return false;
  const stems = COMMAND_STEMS[language];
  return NUMBERISH.test(q) || (stems ? hasStem(q, stems) : false);
}

export const RULES_ENGLISH_SYSTEM =
  'You translate a request to a phone assistant into English. Reply with the English request only.';

/** The request to translate; text to be sent or saved is kept in its own language, in quotes. */
export function rulesEnglishPrompt(question: string): string {
  return `Translate into plain English, keeping names, numbers and times. If the request contains words to send, say or save (a message, an email, a note, a reminder's text), keep those words exactly as written, in their own language, inside double quotes.
Request: ${JSON.stringify(question)}
English:`;
}

/** The model's reply, cleaned; null when it is empty, too long or not a translation. */
export function cleanRulesEnglish(reply: string, question: string): string | null {
  let t = reply.trim().split('\n')[0].trim();
  t = t.replace(/^english:\s*/i, '').trim();
  // A reply wrapped whole in quotes: unwrap it (inner quotes stay).
  if (/^"[^"]*"$/.test(t)) t = t.slice(1, -1).trim();
  if (!t || t.length > question.length * 3 + 40) return null;
  if (t.toLowerCase() === question.trim().toLowerCase()) return null;
  return t;
}
