// Two builds from one codebase (docs/PLAN-v2.md "Distribution", ADR 0008):
// - play (Google Play, default): standard permissions only; messages go through notification
//   replies or open the app ready to send.
// - full (direct-download APK): adds SEND_SMS and the "send for me" Accessibility service.
// Build: ./gradlew assemblePlayRelease | assembleFullRelease (bundlePlayRelease for the store).
const {
  withAppBuildGradle,
  withAndroidManifest,
  withDangerousMod,
  AndroidConfig,
} = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

const MARK = '// sidekick: with-flavours';
const FLAVOURS = `
    ${MARK}
    flavorDimensions "distribution"
    productFlavors {
        play { dimension "distribution" }
        full { dimension "distribution" }
    }
`;

// Both builds: hand-offs to the Clock app, calls after the user taps Call, and seeing which
// messaging/maps apps are installed (Android 11+ package visibility).
const MAIN_PERMISSIONS = [
  'com.android.alarm.permission.SET_ALARM',
  'android.permission.CALL_PHONE',
];
const QUERY_PACKAGES = [
  'com.whatsapp',
  'com.whatsapp.w4b',
  'org.telegram.messenger',
  'org.telegram.messenger.web',
  'org.thoughtcrime.securesms',
  'com.google.android.apps.maps',
  'com.google.android.apps.messaging',
];

const FULL_MANIFEST = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-flavours.js: direct-download ("full") build only. -->
<manifest xmlns:android="http://schemas.android.com/apk/res/android">
  <uses-permission android:name="android.permission.SEND_SMS" />
  <application>
    <meta-data android:name="sidekick.flavour" android:value="full" />
    <service
      android:name="dev.sidekick.engine.integrations.AutoSendService"
      android:exported="false"
      android:label="@string/sidekick_autosend_label"
      android:permission="android.permission.BIND_ACCESSIBILITY_SERVICE">
      <intent-filter>
        <action android:name="android.accessibilityservice.AccessibilityService" />
      </intent-filter>
      <meta-data android:name="android.accessibilityservice" android:resource="@xml/sidekick_autosend" />
    </service>
  </application>
</manifest>
`;

function addFlavours(contents) {
  if (contents.includes(MARK)) return contents;
  const at = contents.indexOf('    defaultConfig {');
  if (at < 0) throw new Error('with-flavours: android.defaultConfig not found in app/build.gradle');
  return (
    contents.slice(0, at) + FLAVOURS.trimStart().replace(/^/, '    ') + '\n' + contents.slice(at)
  );
}

module.exports = function withFlavours(config) {
  config = withAppBuildGradle(config, (c) => {
    c.modResults.contents = addFlavours(c.modResults.contents);
    return c;
  });

  config = withAndroidManifest(config, (c) => {
    const manifest = c.modResults.manifest;
    manifest['uses-permission'] = manifest['uses-permission'] || [];
    for (const name of MAIN_PERMISSIONS) {
      if (!manifest['uses-permission'].some((p) => p.$['android:name'] === name)) {
        manifest['uses-permission'].push({ $: { 'android:name': name } });
      }
    }
    manifest.queries = manifest.queries || [{}];
    const q = manifest.queries[0];
    q.package = q.package || [];
    for (const name of QUERY_PACKAGES) {
      if (!q.package.some((p) => p.$['android:name'] === name))
        q.package.push({ $: { 'android:name': name } });
    }
    AndroidConfig.Manifest.getMainApplicationOrThrow(c.modResults);
    return c;
  });

  return withDangerousMod(config, [
    'android',
    (c) => {
      const dir = path.join(c.modRequest.platformProjectRoot, 'app', 'src', 'full');
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, 'AndroidManifest.xml'), FULL_MANIFEST);
      return c;
    },
  ]);
};

module.exports.addFlavours = addFlavours;
